"""Expand ExtendScript includes at build time. Runtime needs one absolute file."""
from pathlib import Path
import re

def bundle(panel):
    panel=Path(panel).resolve()
    def expand(file,stack=()):
        file=file.resolve()
        if not file.is_relative_to(panel) or file in stack:
            raise ValueError('Invalid or circular JSX include: '+str(file))
        text=file.read_text(encoding='utf-8-sig')
        def include(match):
            target=(file.parent/match.group(1)).resolve()
            return '\n/* bundled: '+target.relative_to(panel).as_posix()+' */\n'+expand(target,stack+(file,))+'\n'
        return re.sub(r'^\s*#include\s+["\']([^"\']+)["\']\s*$',include,text,flags=re.M)
    text='/* Generated by tools/bundle_host.py; edit host.jsx and included sources. */\n'+expand(panel/'jsx/host.jsx')
    if re.search(r'^\s*#include',text,re.M) or '$.evalFile(' in text:
        raise ValueError('Runtime include/evalFile remains in host bundle')
    target=panel/'jsx/host.bundle.jsx';target.write_text(text,encoding='utf-8')
    return target

if __name__=='__main__':
    print(bundle(Path(__file__).resolve().parent.parent/'com.victor.motionviewer'))
